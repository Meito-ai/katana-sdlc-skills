// Single source of truth for the visual-pr block in a PR description: the
// markers that delimit it, the sections the skill fills, and the caps that keep
// it readable. Both readers — ../SKILL.md (prose) and cli.mjs (enforcement) —
// reference these constants rather than restating them.

export const BLOCK_START = '<!-- katana:visual-pr:start v1 -->';
export const BLOCK_END = '<!-- katana:visual-pr:end -->';

export const SUMMARY_HEADING = '## Summary';
export const EVIDENCE_HEADING = '## Evidence';
export const MERGE_DANGER_HEADING = '## Merge Danger';
export const SECTION_HEADINGS = [SUMMARY_HEADING, EVIDENCE_HEADING, MERGE_DANGER_HEADING];

// The description is the first thing a reviewer reads; its rendered height
// decides whether the rest of the page gets read. Lines are the primary cap; the
// byte ceiling only stops a single pathological long line from slipping through.
export const MAX_BLOCK_LINES = 100;
export const MAX_BLOCK_BYTES = 12 * 1024;
export const MAX_SUMMARY_LINES = 50;

// Mermaid that fails to parse renders as an error box in the description, and a
// local run never sees it. These are the diagram types a summary uses.
export const MERMAID_DIAGRAM_KEYWORDS = [
  'sequenceDiagram',
  'stateDiagram-v2',
  'stateDiagram',
  'flowchart',
  'graph',
  'classDiagram',
  'erDiagram',
];

const NO_VISUAL_PATTERN = /^_No visual: (.+?)\._$/;
const DOOR_PATTERN = /^\*\*Door:\*\* (one-way|two-way)$/;
const BLAST_RADIUS_PATTERN = /^\*\*Blast Radius:\*\* \S/;
const SHORT_SHA_LENGTH = 7;

function normalize(text) {
  return text.replaceAll('\r\n', '\n').trim();
}

export function toShortSha(sha) {
  if (!/^[0-9a-f]{7,40}$/.test(sha)) {
    throw new Error(`Not a git object id: ${sha}`);
  }
  return sha.slice(0, SHORT_SHA_LENGTH);
}

export function renderStampLine(sha) {
  return `_Generated by visual-pr for \`${toShortSha(sha)}\`; a refresh replaces this block, so edit outside it._`;
}

// Yields each line with whether it sits inside a code fence (fence lines
// included), so a `## ` inside a diff or a tree is never read as a heading.
function* linesWithFenceState(lines) {
  let inFence = false;
  for (const [index, line] of lines.entries()) {
    const isFence = line.trim().startsWith('```');
    yield { inFence: inFence || isFence, index, line };
    if (isFence) {
      inFence = !inFence;
    }
  }
}

export function lintMermaidFences(content) {
  const lines = normalize(content).split('\n');
  let openedAt = null;
  let expectDiagramKeyword = false;

  for (const [index, line] of lines.entries()) {
    const trimmed = line.trim();

    if (expectDiagramKeyword) {
      const keyword = trimmed.split(/\s/)[0];
      if (!MERMAID_DIAGRAM_KEYWORDS.includes(keyword)) {
        throw new Error(
          `Mermaid fence at line ${openedAt + 1} starts with "${trimmed || '(blank)'}" — ` +
            `expected one of: ${MERMAID_DIAGRAM_KEYWORDS.join(', ')}`,
        );
      }
      expectDiagramKeyword = false;
      continue;
    }

    if (!trimmed.startsWith('```')) {
      continue;
    }

    if (openedAt === null) {
      openedAt = index;
      expectDiagramKeyword = trimmed === '```mermaid';
      continue;
    }

    openedAt = null;
  }

  // An unterminated `mermaid` fence with nothing after it is both unclosed and
  // empty; "empty" is the more precise diagnosis, so report it first.
  if (expectDiagramKeyword) {
    throw new Error('Mermaid fence is empty');
  }
  if (openedAt !== null) {
    throw new Error(`Unclosed code fence opened at line ${openedAt + 1}`);
  }
}

// Splits the content on its level-2 headings, which must be exactly the three
// sections, in order, with nothing before the first.
export function splitSections(content) {
  const lines = normalize(content).split('\n');
  const headings = [];

  for (const { inFence, index, line } of linesWithFenceState(lines)) {
    if (!inFence && /^##\s/.test(line)) {
      headings.push({ index, text: line.trim() });
    }
  }

  const found = headings.map(({ text }) => text);
  if (found.join('\n') !== SECTION_HEADINGS.join('\n')) {
    throw new Error(
      `The block holds exactly ${SECTION_HEADINGS.join(', ')}, in that order; found ${found.join(', ') || 'no sections'}`,
    );
  }
  if (lines.slice(0, headings[0].index).some((line) => line.trim() !== '')) {
    throw new Error(`Content must start with ${SUMMARY_HEADING}`);
  }

  return Object.fromEntries(
    headings.map(({ index, text }, position) => {
      const end = headings[position + 1]?.index ?? lines.length;
      return [text, lines.slice(index + 1, end).filter((line) => line.trim() !== '')];
    }),
  );
}

function assertSummary(lines) {
  const hasVisual = lines.some((line) => line.trim().startsWith('```'));
  const noVisual = lines.find((line) => NO_VISUAL_PATTERN.test(line.trim()));

  if (!hasVisual && !noVisual) {
    throw new Error(`${SUMMARY_HEADING} needs a fenced visual, or the line _No visual: <reason>._`);
  }
  if (noVisual && /[.!?]$/.test(noVisual.trim().match(NO_VISUAL_PATTERN)[1])) {
    throw new Error(`No-visual reason must not end with punctuation: ${noVisual.trim()}`);
  }
  if (lines.length > MAX_SUMMARY_LINES) {
    throw new Error(`${SUMMARY_HEADING} is ${lines.length} lines, over the ${MAX_SUMMARY_LINES}-line cap`);
  }
}

function assertEvidence(lines) {
  for (const label of ['**Before:**', '**After:**']) {
    if (!lines.some((line) => line.includes(label))) {
      throw new Error(`${EVIDENCE_HEADING} must show ${label}`);
    }
  }
}

function assertMergeDanger(lines) {
  if (!lines.some((line) => DOOR_PATTERN.test(line.trim()))) {
    throw new Error(`${MERGE_DANGER_HEADING} needs a line **Door:** one-way, or **Door:** two-way`);
  }
  if (!lines.some((line) => BLAST_RADIUS_PATTERN.test(line.trim()))) {
    throw new Error(`${MERGE_DANGER_HEADING} needs a line **Blast Radius:** <one word>`);
  }
}

function assertCaps(block) {
  const lines = block.split('\n').length;
  if (lines > MAX_BLOCK_LINES) {
    throw new Error(
      `The block is ${lines} lines, over the ${MAX_BLOCK_LINES}-line cap. ` +
        'Cut the summary to one visual, or move detail into a <details> block.',
    );
  }

  const bytes = Buffer.byteLength(block, 'utf8');
  if (bytes > MAX_BLOCK_BYTES) {
    throw new Error(`The block is ${bytes} bytes, over the ${MAX_BLOCK_BYTES}-byte cap`);
  }
}

export function buildBlock({ content, sha }) {
  const normalized = normalize(content);
  if (!normalized) {
    throw new Error('Content is empty');
  }
  if (normalized.includes('katana:visual-pr')) {
    throw new Error('Content must not carry the block markers; the CLI adds them');
  }

  lintMermaidFences(normalized);
  const sections = splitSections(normalized);
  assertSummary(sections[SUMMARY_HEADING]);
  assertEvidence(sections[EVIDENCE_HEADING]);
  assertMergeDanger(sections[MERGE_DANGER_HEADING]);

  const block = [BLOCK_START, normalized, '', renderStampLine(sha), BLOCK_END].join('\n');
  assertCaps(block);
  return block;
}
